use super::super::models::Project;
use crate::shared::models::Outcome;
use crate::shared::paths::{guarded_path, replace_file};
use std::{fs, io, path::Path};

pub fn sync_project(project: &Project, check: bool) -> Outcome<()> {
    let content = native_configuration(project);
    let filename = guarded_path(&project.root, Path::new("gdstyle.toml"))?;
    let legacy = guarded_path(&project.root, Path::new(".gdstyle.toml"))?;
    let current = match fs::read_to_string(&filename) {
        Ok(text) => Some(text.replace("\r\n", "\n")),
        Err(error) if error.kind() == io::ErrorKind::NotFound => None,
        Err(error) => return Err(error.into()),
    };
    if check {
        if current.as_deref() != Some(content.as_str()) {
            return Err("Stale gdstyle.toml; run godot-llm-lint sync".into());
        }
    } else if current.as_deref() != Some(content.as_str()) {
        if legacy.exists() {
            return Err("Competing .gdstyle.toml; remove it before sync".into());
        }
        replace_file(&filename, content.as_bytes())?;
    }
    if legacy.exists() {
        return Err("Competing .gdstyle.toml".into());
    }
    Ok(())
}

fn native_configuration(project: &Project) -> String {
    let mut content =
        String::from("# Generated by godot-llm-lint; edit llm-lint.godot.toml.\nuse_tabs = true\n");
    for (key, value) in &project.settings.style {
        content.push_str(&format!("{key} = {value}\n"));
    }
    let excluded: Vec<_> = [".godot", ".git", ".tools", ".build"]
        .into_iter()
        .chain(
            project
                .settings
                .excluded
                .iter()
                .map(|entry| entry.path.as_str()),
        )
        .collect();
    content.push_str(&format!("exclude = {}\n", serde_json::json!(excluded)));
    content.push_str(&format!(
        "include = {}\n",
        serde_json::json!(project.settings.plugin_roots)
    ));
    content.push_str("\n[rules]\n");
    if let Ok(catalog) = super::super::rules::catalog() {
        for definition in catalog {
            let Some(id) = definition["id"]
                .as_str()
                .filter(|id| id.starts_with("gdstyle/"))
            else {
                continue;
            };
            let default = definition["default"].as_str().unwrap_or("error");
            let configured =
                super::super::rules::level(&project.settings.rules, &[], id, "", default);
            let scoped = project
                .settings
                .overrides
                .iter()
                .any(|entry| entry.rules.contains_key(id));
            content.push_str(&format!(
                "{} = {}\n",
                serde_json::json!(&id[8..]),
                serde_json::json!(if scoped { "warn" } else { configured })
            ));
        }
    }
    content
}
