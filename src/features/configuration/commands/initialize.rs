use super::super::{
    commands::sync_project,
    helpers::{
        configuration_validity, discover_project,
        native::{self, LEGACY_VERSION, NativeOverride, VERSION},
        validate_native_tool,
    },
    models::{Release, Settings},
};
use crate::shared::{
    models::Outcome,
    paths::{guarded_path, replace_file},
};
use sha2::{Digest, Sha256};
use std::{
    fs, io,
    path::{Path, PathBuf},
    process::Command,
};
use toml_edit::{DocumentMut, value};

struct Options {
    source: Option<String>,
    archive: Option<String>,
    config: Option<String>,
    native: Option<NativeOverride>,
}

impl Options {
    fn parse(start: &Path, args: &[String]) -> Outcome<Self> {
        let (mut source, mut archive, mut binary, mut digest, mut config) =
            (None, None, None, None, None);
        for pair in args.chunks(2) {
            if pair.len() != 2 || pair[1].starts_with("--") {
                return Err("Run godot-llm-lint --help for init options".into());
            }
            let slot = match pair[0].as_str() {
                "--source-root" => &mut source,
                "--gdstyle-archive" => &mut archive,
                "--gdstyle-executable" => &mut binary,
                "--gdstyle-sha256" => &mut digest,
                "--config" => &mut config,
                _ => return Err(format!("Unknown initialization option: {}", pair[0]).into()),
            };
            if slot.replace(pair[1].clone()).is_some() {
                return Err("Repeated initialization option".into());
            }
        }
        if archive.is_some() && binary.is_some() {
            return Err("Choose an archive or an existing executable".into());
        }
        let native = NativeOverride::from_arguments(start, binary, digest)?;
        Ok(Self {
            source,
            archive,
            config,
            native,
        })
    }
}

pub fn sync_initialization(start: &Path, args: &[String]) -> Outcome<()> {
    let options = Options::parse(start, args)?;
    let config = if let Some(path) = &options.config {
        start.join(path)
    } else {
        start
            .ancestors()
            .find(|path| path.join("project.godot").is_file())
            .ok_or("Run init in a Godot project")?
            .join("llm-lint.godot.toml")
    };
    let root = fs::canonicalize(config.parent().ok_or("Missing configuration directory")?)?;
    let config = guarded_path(
        &root,
        Path::new(config.file_name().ok_or("Missing configuration filename")?),
    )?;
    if !guarded_path(&root, Path::new("project.godot"))?.is_file() {
        return Err("Configuration must be beside project.godot".into());
    }
    let style = guarded_path(&root, Path::new("gdstyle.toml"))?;
    let legacy_style = guarded_path(&root, Path::new(".gdstyle.toml"))?;
    let previous = read_optional(&config)?;
    if legacy_style.exists()
        || read_optional(&style)?
            .is_some_and(|text| !text.starts_with("# Generated by godot-llm-lint;"))
    {
        return Err("Existing native configuration conflicts with init; move its settings into llm-lint.godot.toml first".into());
    }
    let mut document = previous
        .as_deref()
        .unwrap_or("version = 1\nsource_roots = [\"src\"]\n")
        .parse::<DocumentMut>()?;
    if let Some(source) = options.source {
        if previous.is_some() {
            return Err("Configuration already exists; edit its source_roots and run sync".into());
        }
        let mut roots = toml_edit::Array::new();
        roots.push(source);
        document["source_roots"] = value(roots);
    }
    let mut settings: Settings = toml_edit::de::from_str(&document.to_string())?;
    if let Some(tool) = &settings.gdstyle
        && tool.version == LEGACY_VERSION
    {
        validate_native_tool(tool, LEGACY_VERSION)?;
        // Legacy paths and digests describe the old release, never an executable to run.
        settings.gdstyle = None;
    }
    configuration_validity(&root, &settings)?;
    provision(
        &root,
        start,
        options.archive.as_deref(),
        options.native.as_ref(),
    )?;
    if settings.gdstyle.as_ref().is_none_or(|native| !native.auto) {
        document["gdstyle"] = toml_edit::Item::Table(toml_edit::Table::new());
        document["gdstyle"]["version"] = value(VERSION);
        document["gdstyle"]["auto"] = value(true);
    }
    let updated = document.to_string();
    if previous.as_deref() != Some(&updated) {
        replace_file(&config, updated.as_bytes())?;
    }
    let result =
        discover_project(&root, Some(&config)).and_then(|project| sync_project(&project, false));
    if result.is_err() && previous.as_deref() != Some(&updated) {
        if let Some(previous) = previous {
            replace_file(&config, previous.as_bytes())?;
        } else {
            fs::remove_file(&config)?;
        }
    }
    result
}

fn read_optional(path: &Path) -> Outcome<Option<String>> {
    match fs::read_to_string(path) {
        Ok(text) => Ok(Some(text)),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(error.into()),
    }
}

fn install_archive(
    start: &Path,
    archive: Option<&str>,
    release: &Release,
    directory: &Path,
) -> Outcome<PathBuf> {
    let filename = directory.join(&release.archive_name);
    if let Some(archive) = archive {
        let archive = fs::canonicalize(start.join(archive))?;
        if !archive.is_file() {
            return Err("Expected a regular gdstyle archive".into());
        }
        fs::copy(archive, &filename)?;
    } else {
        let curl = if cfg!(windows) { "curl.exe" } else { "curl" };
        let status = Command::new(native::system_tool(curl)?)
            .current_dir(directory)
            .args([
                "-q",
                "--fail",
                "--location",
                "--proto",
                "=https",
                "--proto-redir",
                "=https",
                "--retry",
                "2",
                "--max-time",
                "60",
                "--output",
            ])
            .arg(&filename)
            .arg(&release.url)
            .status()?;
        if !status.success() {
            return Err("gdstyle download failed; retry init or use --gdstyle-archive".into());
        }
    }
    let hash = format!("{:x}", Sha256::digest(fs::read(&filename)?));
    if hash != release.archive_sha256 {
        return Err("gdstyle archive checksum mismatch".into());
    }
    // The embedded archive digest authenticates all archive members before extraction.
    let tar = if cfg!(windows) { "tar.exe" } else { "tar" };
    let status = Command::new(native::system_tool(tar)?)
        .current_dir(directory)
        .arg("-xf")
        .arg(&filename)
        .arg(&release.executable)
        .status()?;
    if !status.success() {
        return Err(
            "Cannot extract pinned gdstyle executable; install tar or supply --gdstyle-executable"
                .into(),
        );
    }
    let binary = guarded_path(directory, Path::new(&release.executable))?;
    set_executable(&binary)?;
    native::verify(&binary, &release.executable_sha256)?;
    Ok(binary)
}

fn provision(
    root: &Path,
    start: &Path,
    archive: Option<&str>,
    supplied: Option<&NativeOverride>,
) -> Outcome<()> {
    let supplied_path = supplied
        .map(|binary| binary.verified_path(root))
        .transpose()?;
    let release = match native::release_for_host() {
        Ok(release) => release,
        Err(_) if supplied_path.is_some() => return Ok(()),
        Err(error) => return Err(error),
    };
    if supplied.is_some_and(|binary| !binary.is_official(&release)) {
        return Ok(());
    }
    let destination = native::cache_path(root, &release)?;
    if supplied_path.is_none()
        && archive.is_none()
        && native::verify(&destination, &release.executable_sha256).is_ok()
    {
        return Ok(());
    }
    let directory = destination
        .parent()
        .ok_or("Missing gdstyle cache directory")?;
    fs::create_dir_all(directory)?;
    let stage = tempfile::tempdir_in(directory)?;
    let candidate = if let Some(binary) = supplied_path {
        binary
    } else {
        install_archive(start, archive, &release, stage.path())?
    };
    let mut staged_binary = tempfile::NamedTempFile::new_in(directory)?;
    io::copy(
        &mut fs::File::open(&candidate)?,
        staged_binary.as_file_mut(),
    )?;
    set_executable(staged_binary.path())?;
    if let Err(error) = staged_binary.persist(&destination)
        && native::verify(&destination, &release.executable_sha256).is_err()
    {
        return Err(error.into());
    }
    native::verify(&destination, &release.executable_sha256)
}

fn set_executable(path: &Path) -> Outcome<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(path, fs::Permissions::from_mode(0o755))?;
    }
    #[cfg(not(unix))]
    let _path = path;
    Ok(())
}
